# ─── API ─────────────────────────────────────────────────

@app.route('/api/models')
def get_models():
    try:
        r = requests.get(f'{OLLAMA_BASE_URL}/api/tags', timeout=5)
        r.raise_for_status()
        data = r.json()
        models = [m['name'] for m in data.get('models', [])]
        return jsonify({'ok': True, 'models': models})
    except requests.exceptions.ConnectionError:
        return jsonify({'ok': False, 'error': 'Cannot connect to Ollama. Make sure it is running.'}), 503
    except Exception as e:
        return jsonify({'ok': False, 'error': str(e)}), 500


@app.route('/api/extract', methods=['POST'])
def extract_text():
    if 'file' not in request.files:
        return jsonify({'ok': False, 'error': 'No file uploaded'}), 400
    file = request.files['file']
    if file.filename == '':
        return jsonify({'ok': False, 'error': 'No file selected'}), 400
    if not allowed_file(file.filename):
        return jsonify({'ok': False, 'error': 'File type not supported'}), 400
    try:
        filename = secure_filename(file.filename)
        text = extract_text_from_file(file, filename)
        return jsonify({'ok': True, 'text': text, 'filename': filename})
    except Exception as e:
        return jsonify({'ok': False, 'error': f'Failed to extract text: {str(e)}'}), 500


@app.route('/api/generate', methods=['POST'])
def generate():
    data = request.get_json()
    content = data.get('content', '').strip()
    model   = data.get('model', '')
    style   = data.get('style', 'explainer')

    if not content:
        return jsonify({'ok': False, 'error': 'No content provided'}), 400
    if not model:
        return jsonify({'ok': False, 'error': 'No model selected'}), 400

    prompt = build_prompt(content, style)

    def stream():
        try:
            resp = requests.post(
                f'{OLLAMA_BASE_URL}/api/generate',
                json={'model': model, 'prompt': prompt, 'stream': True},
                stream=True,
                timeout=120
            )
            resp.raise_for_status()
            for line in resp.iter_lines():
                if line:
                    try:
                        obj = json.loads(line.decode('utf-8'))
                        token = obj.get('response', '')
                        if token:
                            yield f"data: {json.dumps({'token': token})}\n\n"
                        if obj.get('done'):
                            yield f"data: {json.dumps({'done': True})}\n\n"
                    except json.JSONDecodeError:
                        continue
        except requests.exceptions.ConnectionError:
            yield f"data: {json.dumps({'error': 'Lost connection to Ollama'})}\n\n"
        except Exception as e:
            yield f"data: {json.dumps({'error': str(e)})}\n\n"

    return Response(stream_with_context(stream()), mimetype='text/event-stream',
                    headers={'Cache-Control': 'no-cache', 'X-Accel-Buffering': 'no'})


if __name__ == '__main__':
    app.run(debug=True, port=5000, threaded=True)
