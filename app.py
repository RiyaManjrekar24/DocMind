import os
import json
import requests
from flask import Flask, render_template, request, jsonify, Response, stream_with_context
from werkzeug.utils import secure_filename
import PyPDF2
import docx
import io

app = Flask(__name__)
app.config['MAX_CONTENT_LENGTH'] = 32 * 1024 * 1024  # 32MB max upload
app.config['SECRET_KEY'] = 'docmind-secret-key'

OLLAMA_BASE_URL = os.environ.get('OLLAMA_URL', 'http://localhost:11434')

ALLOWED_EXTENSIONS = {'txt', 'pdf', 'doc', 'docx', 'md', 'html', 'csv', 'json'}

def allowed_file(filename):
    return '.' in filename and filename.rsplit('.', 1)[1].lower() in ALLOWED_EXTENSIONS

def extract_text_from_file(file, filename):
    ext = filename.rsplit('.', 1)[1].lower()
    
    if ext == 'pdf':
        reader = PyPDF2.PdfReader(io.BytesIO(file.read()))
        text = ''
        for page in reader.pages:
            text += page.extract_text() + '\n\n'
        return text.strip() or '[No extractable text found in PDF]'
    
    elif ext == 'docx':
        doc = docx.Document(io.BytesIO(file.read()))
        return '\n\n'.join([para.text for para in doc.paragraphs if para.text.strip()])
    
    elif ext in ('txt', 'md', 'html', 'csv', 'json'):
        return file.read().decode('utf-8', errors='ignore')
    
    return file.read().decode('utf-8', errors='ignore')


def build_prompt(content, style):
    styles = {
        'explainer': 'Create a clear, engaging HTML page that explains the content step by step with headings, key concepts highlighted, callout boxes, and helpful examples.',
        'summary':   'Create a concise HTML summary with an executive overview, bullet-point key takeaways, important statistics, and a quick-reference section.',
        'study':     'Create a study guide HTML with sections for key concepts, definitions, important facts, review questions, and a memory-aid summary.',
        'presentation': 'Create a visually structured HTML that reads like slides — each main point as a distinct full-width card with large headings and concise content.',
        'technical': 'Create technical documentation HTML with overview, detailed sections, code blocks where relevant, parameters/options tables, and a reference index.',
    }
    instruction = styles.get(style, styles['explainer'])

    return f"""You are an expert at converting raw content into beautiful, well-structured, standalone HTML pages.

TASK: Convert the content below into a complete, self-contained HTML file.
STYLE: {instruction}

STRICT REQUIREMENTS:
- Output ONLY valid HTML — no markdown fences, no explanation, no preamble
- Start with <!DOCTYPE html> and end with </html>
- Include ALL CSS inside a <style> tag in the <head>
- Use Google Fonts (import via @import in CSS)
- Beautiful modern design: clean typography, good spacing, subtle colors
- Use semantic HTML: header, main, section, article, footer
- Highlight key terms with <mark> or styled <span>
- Include a page header with title and a footer with "Generated by DocMind"
- Make it responsive (mobile-friendly)
- NO external JS dependencies — pure HTML+CSS only in output
- Use tasteful accent colors, cards, and visual hierarchy

CONTENT TO CONVERT:
---
{content[:8000]}
---

OUTPUT (complete HTML file only):"""


